export const getArabicTranslation = (text) => translations[text] || text;

const reverseTranslations = Object.fromEntries(
  Object.entries(translations).map(([source, translated]) => [translated, source])
);

function translateBack(text) {
  if (reverseTranslations[text]) return reverseTranslations[text];
  for (const [source, translated] of Object.entries(translations)) {
    const placeholders = [...translated.matchAll(/\{(\w+)\}/g)];
    if (!placeholders.length) continue;
    let expression = "";
    let offset = 0;
    for (const placeholder of placeholders) {
      expression += translated.slice(offset, placeholder.index).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      expression += "(.+?)";
      offset = placeholder.index + placeholder[0].length;
    }
    expression += translated.slice(offset).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const match = new RegExp(`^${expression}$`).exec(text);
    if (match) {
      let index = 0;
      return source.replace(/\{(\w+)\}/g, () => match[++index]);
    }
  }
  return text;
}

export function useLanguageState() {
  const [language, setLanguage] = useState(() => {
    try {
      return window.localStorage.getItem("hadad-language") === "en" ? "en" : "ar";
    } catch {
      return "ar";
    }
  });
  const languageRef = useRef(language);
  languageRef.current = language;

  const t = useCallback((text, values = {}) => {
    const translated = languageRef.current === "ar"
      ? translations[text] || text
      : /[\u0600-\u06FF]/.test(text) ? translateBack(text) : text;
    return translated.replace(/\{(\w+)\}/g, (match, key) => (
      Object.prototype.hasOwnProperty.call(values, key) ? values[key] : match
    ));
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    document.documentElement.style.direction = language === "ar" ? "rtl" : "ltr";
    document.title = t("Mohamed Hadad | Barber");
    const description = document.querySelector('meta[name="description"]');
    if (description) {
      description.content = t("Discover Mohamed Hadad Barber Shop haircuts and grooming packages. Request your next service in a few easy steps.");
    }
    try {
      window.localStorage.setItem("hadad-language", language);
    } catch {
      // Keep the language selected for this page view if storage is unavailable.
    }
  }, [language, t]);

  return useMemo(() => ({ language, setLanguage, t }), [language, t]);
}
